package com.estivate.context;

import java.sql.ResultSet;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import javax.sql.DataSource;

import com.estivate.Statement;
import com.estivate.index.Annotations;
import com.estivate.index.Annotations.IndexType;
import com.estivate.index.Annotations.TableIndex;
import com.estivate.query.CreateQuery.Index;
import com.estivate.reconciliation.DatabaseColumn;

import lombok.SneakyThrows;

/**
 * PostgreSQL connection: identity columns, information_schema metadata, and index DDL
 * that MySQL-style {@code AUTO_INCREMENT} / inline {@code INDEX} cannot express.
 */
public class PostgreSQLContext extends Context {

	public PostgreSQLContext(DataSource datasource) {
		super(datasource, new PostgreSQLDialect());
	}

	@Override
	protected String runningQueriesSql() {
		return "SELECT pid AS id, usename AS \"user\", client_addr::text AS host, datname AS db, state, query AS sql FROM pg_stat_activity";
	}

	@Override
	protected void appendAutoIncrement(Statement statement) {
		statement.appendQuery("GENERATED BY DEFAULT AS IDENTITY");
	}

	@Override
	protected boolean supportsInlineIndex(IndexType type) {
		return type == IndexType.PRIMARY || type == IndexType.UNIQUE;
	}

	@Override
	protected void appendInlineIndex(Statement statement, Index index) {
		IndexType type = index.getType() != null ? index.getType() : IndexType.DEFAULT;
		if (type == IndexType.UNIQUE) {
			statement.appendQuery("CONSTRAINT");
			statement.appendQuery(nameMapper.mapIndex(index.getName(), type, index.getColumns()));
			statement.appendQuery("UNIQUE");
		}
		else if (type == IndexType.PRIMARY) {
			statement.appendQuery("PRIMARY KEY");
		}
		else {
			super.appendInlineIndex(statement, index);
			return;
		}

		statement.appendQuery("(");
		statement.appendQuery(index.getColumns().stream()
				.map(col -> nameMapper.mapDatabaseField(col.getColumnName()))
				.reduce((left, right) -> left + ", " + right)
				.orElse(""));
		statement.appendQuery(")");
	}

	@Override
	@SneakyThrows
	public boolean removeIndex(Class<?> entity, String name) {
		if (name.equals("PRIMARY")) {
			return false;
		}

		try (ConnectionLease lease = openConnection();
				Statement statement = new Statement(this, lease.getConnection())) {
			statement.appendQuery("DROP INDEX");
			statement.appendQuery(name);
			return statement.executeForValidation();
		}
	}

	@Override
	@SneakyThrows
	public List<String> showTables() {
		try (ConnectionLease lease = openConnection();
				Statement statement = new Statement(this, lease.getConnection(),
						"SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname = current_schema()");
				ResultSet resultSet = statement.executeForResultSet()) {

			List<String> tables = new ArrayList<>();
			while (resultSet.next()) {
				tables.add(resultSet.getString(1).toUpperCase());
			}
			return tables;
		}
	}

	@Override
	@SneakyThrows
	public List<DatabaseColumn> listFields(String tableName) {
		String lookup = tableName.toLowerCase().replace("'", "''");
		try (ConnectionLease lease = openConnection();
				Statement statement = new Statement(this, lease.getConnection())) {

			statement.appendQuery(
					"SELECT column_name, data_type, character_maximum_length, numeric_precision, numeric_scale, "
							+ "is_nullable, column_default, is_identity "
							+ "FROM information_schema.columns "
							+ "WHERE table_schema = current_schema() AND table_name = '" + lookup + "' "
							+ "ORDER BY ordinal_position");

			List<DatabaseColumn> fields = new ArrayList<>();
			for (com.estivate.result.ResultRow row : fetchListAsResults(statement)) {
				String dataType = canonicalType(row.asString("data_type"));
				boolean identity = "YES".equalsIgnoreCase(row.asString("is_identity"));
				Integer length = row.asInteger("character_maximum_length");
				Integer precision = row.asInteger("numeric_precision");
				Integer scale = row.asInteger("numeric_scale");

				Integer dimension = null;
				Integer reportedScale = null;
				if (length != null) {
					dimension = length;
				}
				else if ("DECIMAL".equals(dataType) || "NUMERIC".equals(dataType)) {
					dimension = precision;
					reportedScale = scale;
				}

				fields.add(DatabaseColumn.builder()
						.name(row.asString("column_name"))
						.type(dataType)
						.nullable("YES".equalsIgnoreCase(row.asString("is_nullable")))
						.autoIncrement(identity)
						.defaultValue(identity ? null : row.asString("column_default"))
						.dimension(dimension)
						.scale(reportedScale)
						.build());
			}
			return fields;
		}
	}

	@Override
	@SneakyThrows
	public List<TableIndex> listIndexes(Class<?> entity) {
		String lookup = nameMapper.toTableName(entity).toLowerCase().replace("'", "''");
		try (ConnectionLease lease = openConnection();
				Statement statement = new Statement(this, lease.getConnection())) {

			statement.appendQuery(
					"SELECT i.relname AS index_name, ix.indisunique AS is_unique, ix.indisprimary AS is_primary, "
							+ "a.attname AS column_name "
							+ "FROM pg_class t "
							+ "JOIN pg_namespace n ON n.oid = t.relnamespace "
							+ "JOIN pg_index ix ON t.oid = ix.indrelid "
							+ "JOIN pg_class i ON i.oid = ix.indexrelid "
							+ "JOIN LATERAL unnest(ix.indkey) WITH ORDINALITY AS cols(attnum, ord) ON cols.attnum > 0 "
							+ "JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = cols.attnum "
							+ "WHERE n.nspname = current_schema() AND t.relname = '" + lookup + "' "
							+ "ORDER BY i.relname, cols.ord");

			Map<String, List<com.estivate.result.ResultRow>> byName = new LinkedHashMap<>();
			for (com.estivate.result.ResultRow row : fetchListAsResults(statement)) {
				byName.computeIfAbsent(row.asString("index_name"), key -> new ArrayList<>()).add(row);
			}

			List<TableIndex> indexes = new ArrayList<>();
			for (Map.Entry<String, List<com.estivate.result.ResultRow>> entry : byName.entrySet()) {
				com.estivate.result.ResultRow first = entry.getValue().get(0);
				boolean primary = isPgTrue(first.asString("is_primary"));
				boolean unique = isPgTrue(first.asString("is_unique"));

				IndexType type;
				String name;
				if (primary) {
					type = IndexType.PRIMARY;
					name = "PRIMARY";
				}
				else if (unique) {
					type = IndexType.UNIQUE;
					name = entry.getKey().toUpperCase();
				}
				else {
					type = IndexType.DEFAULT;
					name = entry.getKey().toUpperCase();
				}

				List<Annotations.IndexColumn> columns = new ArrayList<>();
				for (com.estivate.result.ResultRow row : entry.getValue()) {
					String columnName = row.asString("column_name");
					String entityField = findEntityName(entity, columnName);
					if (entityField == null) {
						entityField = findEntityName(entity, columnName.toUpperCase());
					}
					if (entityField == null) {
						entityField = columnName;
					}
					columns.add(Annotations.ColumnIndex(entityField, 0));
				}
				indexes.add(Annotations.CompositeIndex(name, type, columns));
			}
			return indexes;
		}
	}

	private static String canonicalType(String dataType) {
		if (dataType == null) {
			return null;
		}
		switch (dataType.toLowerCase()) {
			case "integer":
				return "INTEGER";
			case "bigint":
				return "BIGINT";
			case "smallint":
				return "SMALLINT";
			case "real":
				return "REAL";
			case "double precision":
				return "DOUBLE PRECISION";
			case "numeric":
				return "DECIMAL";
			case "boolean":
				return "BOOLEAN";
			case "character varying":
			case "character":
				return "VARCHAR";
			case "text":
				return "TEXT";
			case "bytea":
				return "BYTEA";
			case "date":
				return "DATE";
			case "timestamp without time zone":
			case "timestamp with time zone":
				return "TIMESTAMP";
			default:
				return dataType.toUpperCase();
		}
	}

	private static boolean isPgTrue(String value) {
		return "t".equalsIgnoreCase(value) || "true".equalsIgnoreCase(value) || "1".equals(value);
	}

}
